/** Tên miền của link, bỏ "www.", viết thường. Link hỏng hoặc không phải http(s) → null. */
export function hostOf(url: string | null | undefined): string | null {
  if (!url) return null
  try {
    const u = new URL(url)
    if (u.protocol !== 'http:' && u.protocol !== 'https:') return null
    return u.hostname.toLowerCase().replace(/^www\./, '') || null
  } catch {
    return null
  }
}

/** Thương hiệu khớp tên miền (khớp đúng tên miền hoặc tên miền con), không khớp → null. */
export function brandOf(url: string | null | undefined): SiteBrand | null {
  const host = hostOf(url)
  if (!host) return null
  return SITE_BRANDS.find((b) => b.hosts.some((h) => host === h || host.endsWith(`.${h}`))) ?? null
}

/** Nhãn ngắn cho link: tên thương hiệu nếu biết; Google Docs tách Docs/Sheets/Slides/Forms theo đường dẫn; còn lại là tên miền. */
export function siteLabel(url: string | null | undefined): string {
  const brand = brandOf(url)
  if (brand?.key === 'googledocs') {
    const path = (() => {
      try {
        return new URL(url as string).pathname
      } catch {
        return ''
      }
    })()
    if (path.startsWith('/spreadsheets')) return 'Google Sheets'
    if (path.startsWith('/presentation')) return 'Google Slides'
    if (path.startsWith('/forms')) return 'Google Forms'
    return 'Google Docs'
  }
  return brand?.label ?? hostOf(url) ?? 'Link'
}

export interface SiteIconProps {
  url: string | null | undefined
  /** Cạnh icon tính bằng px, mặc định 16. */
  size?: number
  className?: string
}

/** Icon của trang web. Có `title` là tên trang để rê chuột thấy, `aria-hidden` vì chữ bên cạnh đã nói rõ. */
export function SiteIcon({ url, size = 16, className = '' }: SiteIconProps) {
  const brand = brandOf(url)
  const title = siteLabel(url)
  if (brand) {
    return (
      <svg
        role="img"
        aria-hidden="true"
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill={brand.color}
        className={`shrink-0 ${className}`}
      >
        <title>{title}</title>
        <path d={brand.path} />
      </svg>
    )
  }
  const host = hostOf(url)
  if (host) {
    return (
      <span
        aria-hidden="true"
        title={title}
        className={`inline-flex shrink-0 items-center justify-center rounded-full bg-slate-200 font-semibold uppercase text-slate-600 ${className}`}
        style={{ width: size, height: size, fontSize: Math.max(10, Math.round(size * 0.6)) }}
      >
        {host.charAt(0)}
      </span>
    )
  }
  return (
    <svg
      aria-hidden="true"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="#64748b"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`shrink-0 ${className}`}
    >
      <title>{title}</title>
      <path d="M10 13a5 5 0 0 0 7.54.54l3-3a5 5 0 0 0-7.07-7.07l-1.72 1.71" />
      <path d="M14 11a5 5 0 0 0-7.54-.54l-3 3a5 5 0 0 0 7.07 7.07l1.71-1.71" />
    </svg>
  )
}
